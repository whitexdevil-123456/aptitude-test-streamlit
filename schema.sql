-- Class Test Portal schema for Supabase PostgreSQL.
-- Run the complete file in Supabase Dashboard -> SQL Editor.
-- The app uses the service-role key server-side only; never place it in frontend code.

create extension if not exists pgcrypto;

create table if not exists public.students (
    id uuid primary key default gen_random_uuid(),
    roll_number text not null unique,
    full_name text not null,
    pin_hash text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.questions (
    id bigint generated by default as identity primary key,
    category text not null check (category in ('aptitude', 'programming')),
    question_type text not null check (question_type in ('mcq', 'short', 'coding')),
    prompt text not null,
    options jsonb not null default '[]'::jsonb,
    correct_answer text,
    expected_output text,
    topic text,
    difficulty text not null default 'Medium',
    marks numeric(8,2) not null default 1 check (marks > 0),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint question_category_type_check check (
        (category = 'aptitude' and question_type in ('mcq', 'short')) or
        (category = 'programming' and question_type = 'coding')
    )
);

create table if not exists public.exam_settings (
    category text primary key check (category in ('aptitude', 'programming')),
    title text not null,
    duration_minutes integer not null default 30 check (duration_minutes between 1 and 300),
    questions_per_attempt integer not null default 10 check (questions_per_attempt between 1 and 200),
    is_active boolean not null default true,
    updated_at timestamptz not null default now()
);

create table if not exists public.attempts (
    id uuid primary key default gen_random_uuid(),
    student_id uuid not null references public.students(id),
    category text not null check (category in ('aptitude', 'programming')),
    status text not null default 'in_progress' check (status in ('in_progress', 'submitted', 'expired')),
    started_at timestamptz not null default now(),
    deadline_at timestamptz not null,
    submitted_at timestamptz,
    score numeric(10,2) not null default 0,
    max_score numeric(10,2) not null default 0
);

create table if not exists public.attempt_questions (
    id bigint generated by default as identity primary key,
    attempt_id uuid not null references public.attempts(id) on delete cascade,
    question_id bigint not null references public.questions(id),
    display_order integer not null,
    marks numeric(8,2) not null default 1 check (marks > 0),
    unique (attempt_id, question_id),
    unique (attempt_id, display_order)
);

create table if not exists public.answers (
    id bigint generated by default as identity primary key,
    attempt_id uuid not null references public.attempts(id) on delete cascade,
    question_id bigint not null references public.questions(id),
    answer_text text,
    code_answer text,
    output_answer text,
    is_correct boolean,
    awarded_marks numeric(8,2) not null default 0 check (awarded_marks >= 0),
    graded_at timestamptz,
    updated_at timestamptz not null default now(),
    unique (attempt_id, question_id)
);

create index if not exists idx_questions_category_active on public.questions(category, is_active);
create index if not exists idx_attempts_student_started on public.attempts(student_id, started_at desc);
create index if not exists idx_attempts_status_deadline on public.attempts(status, deadline_at);
create index if not exists idx_attempt_questions_attempt on public.attempt_questions(attempt_id, display_order);
create index if not exists idx_answers_attempt on public.answers(attempt_id);

-- Prevent two simultaneous in-progress attempts for the same student and section.
create unique index if not exists idx_one_active_attempt_per_student_section
on public.attempts(student_id, category) where status = 'in_progress';

-- Enable Row Level Security. No public/anon policies are intentionally created.
-- The Python server uses the secret service-role key, which bypasses RLS. Keep it private.
alter table public.students enable row level security;
alter table public.questions enable row level security;
alter table public.exam_settings enable row level security;
alter table public.attempts enable row level security;
alter table public.attempt_questions enable row level security;
alter table public.answers enable row level security;

